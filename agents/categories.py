def notice_text(org: str, date: str, item_name: str, color: str, public: dict) -> str:
    """공고 상세내용. 특이사항에는 공개 특징만 '항목 값 · 항목 값'으로 (없으면 기존처럼 '없음').
    물품명에 이미 들어간 값(예: 모델명이 든 '애플 에어팟 맥스 헤드폰')은 되풀이하지 않는다.
    제조사·모델명은 물품명이 담당(영문·한글이 섞여 글자 비교로는 못 거름). 매칭용 공개 특징에는 그대로 남는다."""
    name = item_name.replace(" ", "").lower()
    extra = {k: v for k, v in public.items() if k not in NAME_FIELDS and v.replace(" ", "").lower() not in name}
    special = " · ".join(f"{k} {v}" for k, v in extra.items()) or "없음"
    return NOTICE_TEMPLATE.format(org=org, date=date.replace("-", "."), item_name=item_name, color=color, special=special)
